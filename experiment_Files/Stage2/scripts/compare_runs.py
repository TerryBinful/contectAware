#!/usr/bin/env python3
"""Compare the primary run with the sensitivity runs (all numbers read from results/<label>/).

    python scripts/compare_runs.py [--labels main sens_motion_dynamics ...]
Writes results/SENSITIVITY_SUMMARY.md and results/sensitivity_summary.csv.
"""
import argparse
import json
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from ca_stability.mdtable import df_to_markdown  # noqa: E402
from ca_stability.mechanisms.registry import LABEL, ORDER  # noqa: E402

RES = Path(__file__).resolve().parents[1] / "results"
DEFAULT = ["main", "sens_motion_dynamics", "sens_original_features", "sens_all_participants"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--labels", nargs="*", default=DEFAULT)
    a = ap.parse_args()
    runs, mech = [], []
    for lab in a.labels:
        d = RES / lab
        if not (d / "mechanism_metrics.csv").exists():
            print(f"skip {lab}: no completed run")
            continue
        meta = json.loads((d / "experiment_metadata.json").read_text())
        e1 = json.loads((d / "baseline" / "exp1_summary.json").read_text())
        ops = pd.read_csv(d / "operating_points.csv")
        sel = ops.selection_condition.iloc[0]
        st = pd.read_csv(d / "statistical_tests.csv")
        pr = st[(st.target_name == "primary") & (st.family == "primary")]
        runs.append({"run": lab, "status": meta["status"], "features": meta["feature_set"]["name"],
                     "n_features": e1["n_features"], "cohort": meta["config"]["cohort"]["mode"],
                     "n_genuine": e1["n_genuine_users"], "median_test_AUC": e1["test_auc"]["median"],
                     "median_test_EER": e1["test_eer"]["median"], "gate": e1["gate"]["passed"],
                     "selection_condition": sel, "best_smoother": ops.best_smoother.iloc[0],
                     "primary_contrast_median_diff": float(pr.median_diff.iloc[0]) if len(pr) else None,
                     "primary_contrast_p": float(pr.p_value.iloc[0]) if len(pr) else None})
        mm = pd.read_csv(d / "mechanism_metrics.csv")
        mm = mm[(mm.partition == "test") & (mm.target_name == "primary")]
        for r in mm.itertuples():
            rd = r._asdict()
            mech.append({"run": lab, "mechanism": r.mechanism,
                         "FAR_frame": rd[f"{sel}_far_frame__median"], "FRR_time": rd["frr_time__median"],
                         "detection_delay": rd[f"{sel}_ania_median__median"], "miss_rate": rd[f"{sel}_miss_rate__median"],
                         "false_locks_per_hour_pooled": r.false_locks_per_hour_pooled,
                         "pingpong_per_hour": r.pingpong_per_hour__median})
    runs, mech = pd.DataFrame(runs), pd.DataFrame(mech)
    mech.to_csv(RES / "sensitivity_summary.csv", index=False)
    lines = ["# Sensitivity summary (auto-generated by scripts/compare_runs.py)", "",
             "Primary = `main`. Sensitivity runs change ONE pre-declared design element each; they are robustness "
             "checks, not alternative primary results. Test partition, primary target, medians over genuine users.", "",
             "## Score generator and primary contrast", "", df_to_markdown(runs), ""]
    for metric in ["FAR_frame", "FRR_time", "detection_delay", "false_locks_per_hour_pooled", "pingpong_per_hour"]:
        w = mech.pivot(index="mechanism", columns="run", values=metric).reindex([m for m in ORDER if m in set(mech.mechanism)])
        w = w[[c for c in runs.run if c in w.columns]]
        w.index = [LABEL[m] for m in w.index]
        lines += [f"## {metric}", "", df_to_markdown(w.reset_index().rename(columns={"index": "mechanism"})), ""]
    (RES / "SENSITIVITY_SUMMARY.md").write_text("\n".join(lines) + "\n")
    print((RES / "SENSITIVITY_SUMMARY.md").read_text()[:3000])


if __name__ == "__main__":
    main()
