"""Stage I — RESULTS_REPORT.md, generated from result files only. No mechanism is declared a
'winner'; results are described per outcome family with uncertainty."""
from __future__ import annotations

import json

import numpy as np
import pandas as pd

from .mechanisms.registry import FAMILY, LABEL, ORDER


def _md(r, name):
    p = r.res / "tables" / f"{name}.md"
    return p.read_text() if p.exists() else "_(table not generated)_\n"


def _p(x):
    return "—" if x is None or (isinstance(x, float) and np.isnan(x)) else (f"{x:.3g}" if x >= 0.001 else "<0.001")


def write_report(r):
    res, cfg = r.res, r.cfg
    meta = json.loads((res / "experiment_metadata.json").read_text())
    ds = json.loads((res / "dataset_audit" / "dataset_summary.json").read_text())
    e1 = json.loads((res / "baseline" / "exp1_summary.json").read_text())
    cov = json.loads((res / "benchmark" / "coverage.json").read_text())
    leak = json.loads((res / "benchmark" / "leakage_checks.json").read_text())
    san = json.loads((res / "benchmark" / "sanity_checks.json").read_text())
    ops = pd.read_csv(res / "operating_points.csv")
    st = pd.read_csv(res / "statistical_tests.csv")
    man = pd.read_csv(res / "benchmark" / "manifest.csv")
    sel = ops.selection_condition.iloc[0]
    best = ops.best_smoother.iloc[0]
    status = cfg["experiment"]["status"]
    fails = json.loads((res / "failures.json").read_text()) if (res / "failures.json").exists() else []

    prim = st[(st.target_name == "primary") & (st.family == "primary")]
    pr = prim.iloc[0] if len(prim) else None
    h3 = st[(st.target_name == "primary") & (st.family == "H3_component_ablation")]
    om = st[(st.target_name == "primary") & (st.family == "omnibus")]
    h4 = st[(st.target_name == "primary") & (st.family == "H4_context_matching")]
    t9 = pd.read_csv(res / "tables" / "T9_operating_point_transfer.csv")
    t9p = t9[t9.target_name == "primary"]

    L = []
    add = L.append
    banner = {"pilot": "> **PILOT RUN — not evidence.** A seeded subset of genuine users; used only to check the pipeline and runtime.",
              "sensitivity": "> **SENSITIVITY ANALYSIS** — a pre-registered deviation from the primary configuration; read alongside the primary run.",
              "primary": "> **PRIMARY RUN** — configuration, split, benchmark and operating points frozen before test evaluation."}[status]
    add(f"# Stage 2 results — decision-layer stabilisation mechanisms ({cfg['experiment']['label']})\n")
    add("_Auto-generated by `ca_stability.report` from the files in this directory. Do not edit by hand; re-run the pipeline._\n")
    add(banner + "\n")
    add(f"- Experiment id: `{meta['experiment_id']}`  \n- Git commit: `{meta['git_commit']}` (code dirty: {meta['code_dirty']})  \n"
        f"- Code fingerprint: `{meta['code_fingerprint_sha256'][:16]}`  \n- Config hash: `{meta['config_hash']}`  \n"
        f"- Generated: {meta['generated_utc']}  \n- Reproduce: `{meta['reproduction_command']}` (from `experiment_Files/Stage2/`)\n")
    if fails:
        add(f"**Recorded failures during this run: {len(fails)}** — see `failures.json`.\n")

    add("## 1. Research question and hypothesis\n")
    add("**RQ.** At a matched genuine false-lock rate, how do decision-layer stabilisation mechanisms differ in security "
        "(impostor frames accepted, genuine frames rejected), stability (transitions, ping-pong) and responsiveness "
        "(detection and recovery delay) when all consume the same fixed authentication-score stream?\n")
    add("**Working hypothesis (not assumed).** Mechanisms exhibit different trade-offs at comparable operating points. "
        "No mechanism is presumed best; a null result is a valid outcome.\n")

    add("## 2. Dataset and participants\n")
    add(_md(r, "T1_dataset"))
    add(f"\nThe cohort rule keeps participants whose inter-frame gaps are regular (1 frame ≈ {ds['frame_period_s_used']:.0f} s), "
        f"so frame-based parameters have a stable time meaning. Full audit: `dataset_audit/DATASET_AUDIT_REPORT.md`.\n")

    add("## 3. Fixed score generator (Exp 1 gate)\n")
    add(f"Per-user HistGradientBoosting verifier on `{cfg['features']['set']}` features "
        f"({e1['n_features']} features), trained on the user's first {int(cfg['periods']['fractions'][0]*100)}% of frames vs "
        f"training-role impostors; Platt-calibrated on validation. Impostors in calibration and test are **unseen**.\n")
    add(_md(r, "T3_exp1_classifier"))
    add(f"\nGate: {e1['gate']['criterion']} → value {e1['gate']['value']:.3f} → **{'PASSED' if e1['gate']['passed'] else 'FAILED'}**.\n")

    add("## 4. Transition benchmark\n")
    add(f"- Genuine streams: {len(pd.read_csv(res / 'benchmark' / 'genuine_streams.csv'))}; spliced sequences: {len(man)} "
        f"(val {int((man.partition == 'val').sum())}, test {int((man.partition == 'test').sum())}).\n"
        f"- Block lengths L (frames): {cfg['benchmark']['L_frames']}; conditions: {cfg['benchmark']['conditions']} "
        f"(X = cross-context, M = context-matched on dominant activity/placement/location label).\n"
        f"- Context-matched coverage (min over partitions): {cov.get('M_coverage_min', float('nan')):.3f} → selection condition **{sel}**.\n"
        f"- Leakage checks: {'**all passed**' if leak['all_passed'] else '**FAILED**'} "
        f"({', '.join(k for k, v in leak.items() if isinstance(v, dict))}).\n"
        f"- Sanity (spec §9): threshold X detection median {san['check2_threshold_X_ania_median_frames']:.2f} frames "
        f"(check 2 {'passed' if san['check2_passed'] else 'FAILED'}); M ≥ X: {san['check3_passed']}.\n")

    add("## 5. Mechanisms and matched operating points\n")
    add("| Mechanism | Family |\n|---|---|\n" + "\n".join(f"| {LABEL[m]} | {FAMILY[m]} |" for m in ORDER if m in set(ops.mechanism)) + "\n")
    add(f"\nEach mechanism's full grid was swept on **validation** only. Selected cell = admissible cell (pooled false-lock rate "
        f"within ±{cfg['operating_point']['tolerance']:.0%} of the target and mean false-lock duration ≤ "
        f"{cfg['operating_point']['max_lockout_frames']} frames) with the lowest validation median detection delay in condition {sel} "
        f"(tie-break: lower FAR_frame). `operating_points.csv` was hashed before any test computation "
        f"(`operating_points.frozen.json`). Pre-registered comparator ('best smoother' on validation): **{LABEL.get(best, best)}**.\n")
    add(_md(r, "T4_operating_points"))

    add("\n## 6. Results on the test partition (primary target)\n")
    add(f"Values are medians over genuine users with user-level bootstrap 95% CIs "
        f"({cfg['stats']['bootstrap_reps']} resamples). Frames ≈ minutes.\n")
    add("### 6.1 Security\n" + _md(r, "T5_security"))
    add("\n### 6.2 Stability\n" + _md(r, "T6_stability"))
    add("\n### 6.3 Responsiveness\n" + _md(r, "T7_responsiveness"))
    add("\n### 6.4 Operating-point transfer (validation → test)\n")
    add(f"The false-lock rate was matched on validation. On test, the pooled rate ranged from "
        f"{t9p.test_false_locks_per_hour.min():.3f} to {t9p.test_false_locks_per_hour.max():.3f} per hour "
        f"(target {t9p.target.iloc[0]:.3f}). Comparisons on test are therefore at *approximately* matched, not identical, "
        f"genuine cost; see `tables/T9_operating_point_transfer.md`.\n")

    add("\n## 7. Statistics (unit = genuine user)\n")
    add("### 7.1 Omnibus (Friedman across the nine primary mechanisms)\n" + _md(r, "T8a_friedman"))
    add("\n### 7.2 Planned contrasts\n" + _md(r, "T8b_planned_contrasts"))
    if pr is not None:
        add(f"\n**Pre-registered primary contrast** (hysteresis − {LABEL.get(best, best)}, sustained detection delay, "
            f"condition {sel}): median paired difference {pr.median_diff:.3g} frames "
            f"(95% CI {pr.ci_lo:.3g} to {pr.ci_hi:.3g}), Wilcoxon p = {_p(pr.p_value)}, rank-biserial r = {pr.rank_biserial:.2f}, "
            f"n = {int(pr.n_users)} users → {'difference detected at α = 0.05' if pr.significant else 'no difference detected at α = 0.05'}.\n")
    if len(h3):
        add("\n**H3 component ablation** (hysteresis vs its components, detection delay): " + "; ".join(
            f"{row.comparison}: median diff {row.median_diff:.3g} [{row.ci_lo:.3g}, {row.ci_hi:.3g}], Holm p = {_p(row.p_holm)}"
            for row in h3.itertuples()) + ". H3 is supported only if hysteresis is better than **both** components.\n")
    if len(h4):
        n_sig = int(h4.significant.sum())
        add(f"\n**H4 context matching**: M − X detection delay differed significantly (Holm) for {n_sig} of {len(h4)} mechanisms "
            f"(see T8b).\n")
    if len(om):
        sig = om[om.significant]
        add(f"\nFriedman tests detected differences among mechanisms for {len(sig)} of {len(om)} outcomes "
            f"({', '.join(sig.outcome)}). All mechanism-vs-threshold comparisons (Holm within outcome) are in `tables/T8c_vs_threshold.md`.\n")

    add("\n### 7.3 Pre-registered decision rules (docs/Stage2/PREREGISTRATION_FROZEN.md §5), applied mechanically\n")
    mmp = pd.read_csv(res / "mechanism_metrics.csv")
    mmp = mmp[(mmp.partition == "test") & (mmp.target_name == "primary")].set_index("mechanism")
    dec = []
    a = om[om.outcome == "ania"]
    if len(a):
        dec.append(f"- **H1** (mechanisms differ in detection delay): Friedman p = {_p(a.p_value.iloc[0])} → "
                   f"{'supported' if a.significant.iloc[0] else 'null not rejected'}.")
    if pr is not None:
        ok = bool(pr.significant and pr.median_diff < 0)
        dec.append(f"- **H2** (hysteresis faster than the best smoother, {LABEL.get(best, best)}): "
                   f"{'supported' if ok else 'falsified under the pre-registered rule (non-significant or not faster)'}.")
    if len(h3):
        ok = bool((h3.significant & (h3.rank_biserial < 0)).all()) and len(h3) == 2
        dec.append(f"- **H3** (hysteresis better than both margin-only and dwell-only): {'supported' if ok else 'not supported'} "
                   f"({'; '.join(f'{x.comparison}: Holm p = {_p(x.p_holm)}, r = {x.rank_biserial:.2f}' for x in h3.itertuples())}).")
    col_a, col_f = f"{sel}_ania_median__median", f"{sel}_far_frame__median"
    if "hysteresis" in mmp.index:
        dom = [m for m in ("trust", "sprt") if m in mmp.index and mmp.loc[m, col_a] <= mmp.loc["hysteresis", col_a]
               and mmp.loc[m, col_f] <= mmp.loc["hysteresis", col_f]]
        dec.append(f"- **Handover framing rule** (trust or SPRT at least as good as hysteresis on both test median detection "
                   f"delay and FAR_frame at the matched point): {'triggered by ' + ', '.join(LABEL[m] for m in dom) if dom else 'not triggered'}.")
    if len(h4):
        dec.append(f"- **H4** (M slower than X for every mechanism): {'supported' if bool(h4.significant.all() and (h4.median_diff >= 0).all()) else 'not supported'} "
                   f"({int(h4.significant.sum())}/{len(h4)} significant).")
    add("\n".join(dec) + "\n")
    add("These are statements about the pre-registered rules on this benchmark, not a ranking of mechanisms: "
        "the tables above show that the mechanisms trade security, genuine-user cost and stability differently.\n")

    add("\n## 8. Sensitivity targets\n")
    for tname in [t for t in ops.target_name.unique() if t != "primary"]:
        tv = ops[ops.target_name == tname].target_false_locks_per_hour.iloc[0]
        add(f"\n### {tname} (target {tv:.3g} false locks / h)\n")
        add(_md(r, f"T6_stability_{tname}"))
        add(_md(r, f"T7_responsiveness_{tname}"))

    add("\n## 9. Figures\n")
    for p in sorted((res / "figures").glob("*.png")):
        add(f"- `figures/{p.name}`")
    add("\n## 10. Evidence quality and limitations\n")
    lim = [
        "Identity transitions are **simulated by splicing** frames of different participants; real theft/hand-over (gradual, same device) is not observed.",
        "Each ExtraSensory participant used **their own phone**. Impostor frames therefore come from a different device, so device-specific sensor characteristics may make impostors easier to detect than on a shared device. Absolute detection numbers are likely optimistic; the comparison between mechanisms consumes the same stream and is less affected.",
        f"Decisions occur about once per minute (1 frame ≈ {ds['frame_period_s_used']:.0f} s); nothing here supports sub-minute claims.",
        "The cohort is the regular-cadence subset of a student-heavy convenience sample; generalisation beyond it is untested.",
        "The operating point was matched on validation data; test false-lock rates differ from the target (§6.4).",
        "Context labels are self-reported and sparse; condition M matches the dominant label only.",
        "Mechanism grids are finite; a mechanism's result is conditional on its grid (documented in the config).",
    ]
    if status == "pilot":
        lim.insert(0, "PILOT: only a subset of genuine users; statistical tests are underpowered and reported only to exercise the code.")
    add("\n".join(f"- {x}" for x in lim) + "\n")
    add("\n## 11. Reproducibility\n")
    add(f"- Dataset archive MD5 `{cfg['data']['md5']}`; participant files fingerprint `{meta['dataset']['sha256_of_ids_and_sizes'][:16]}`.\n"
        f"- Split: `participant_split.json` (master seed {cfg['experiment']['seed']}). Benchmark: `benchmark/manifest.csv`, "
        f"score streams in `benchmark/*.parquet` (mechanism results can be re-derived from these without retraining).\n"
        f"- Environment: Python {meta['environment']['python']}; packages {meta['environment']['packages']}.\n")
    (res / "RESULTS_REPORT.md").write_text("\n".join(L) + "\n")
